/* Nạp tin mẫu vào LocalStorage lần đầu (khi chưa có) */
(function () {
    try {
        if (!localStorage.getItem("news")) {
            localStorage.setItem("news", JSON.stringify(TIN_MAU));
        }
    } catch (e) {}
})();

function thoatTin(s) {
    return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

function layTinTuc() {
    try {
        var ds = JSON.parse(localStorage.getItem("news"));
        return Array.isArray(ds) ? ds : [];
    } catch (e) {
        return [];
    }
}

function layTinTheoId(id) {
    id = parseInt(id, 10);
    return layTinTuc().filter(function (t) { return t.id === id; })[0] || null;
}

/* Tin mới nhất xếp trước. loai: "tintuc", "khuyenmai" hoặc bỏ trống = tất cả */
function laySapXepTin(loai) {
    return layTinTuc()
        .filter(function (t) { return !loai || t.type === loai; })
        .sort(function (a, b) { return a.date < b.date ? 1 : (a.date > b.date ? -1 : 0); });
}

function dinhDangNgay(iso) {
    var p = String(iso).split("-");
    return p.length === 3 ? p[2] + "/" + p[1] + "/" + p[0] : iso;
}

function taoTheTin(t) {
    var nhan = t.type === "khuyenmai" ? "Khuyến mãi" : "Tin tức";
    return '<div class="col-12 col-md-6 col-lg-4 mb-4">' +
           '<div class="card h-100 product-card">' +
           '<img src="' + thoatTin(t.image) + '" class="card-img-top" alt="' + thoatTin(t.title) + '">' +
           '<div class="card-body d-flex flex-column">' +
           '<div class="small text-muted mb-1"><span class="badge bg-secondary me-2">' + nhan + '</span>' + dinhDangNgay(t.date) + '</div>' +
           '<h5 class="card-title fs-6 fw-bold">' + thoatTin(t.title) + '</h5>' +
           '<p class="card-text small text-secondary">' + thoatTin(t.summary) + '</p>' +
           '<a href="chitiet-tintuc.html" class="btn btn-orange btn-sm mt-auto align-self-start tin-link" data-id="' + t.id + '">Đọc tiếp</a>' +
           '</div></div></div>';
}

/* Trang chủ (A) gọi: hienTinMoi(3) -> vẽ vào #home-news-container */
function hienTinMoi(soLuong) {
    var vung = document.getElementById("home-news-container");
    if (!vung) { return; }
    var ds = laySapXepTin().slice(0, soLuong || 3);
    vung.innerHTML = ds.length ? ds.map(taoTheTin).join("") : '<p class="text-muted">Chưa có tin tức.</p>';
}

/* tintuc.html: danh sách + bộ lọc */
function hienDanhSachTin(loai) {
    var vung = document.getElementById("news-list");
    if (!vung) { return; }
    var ds = laySapXepTin(loai);
    vung.innerHTML = ds.length ? ds.map(taoTheTin).join("") : '<p class="text-muted">Chưa có tin trong mục này.</p>';
    var nut = document.querySelectorAll("#news-filter button");
    for (var i = 0; i < nut.length; i++) {
        var dangChon = (nut[i].getAttribute("data-loai") || "") === (loai || "");
        nut[i].classList.toggle("btn-orange", dangChon);
        nut[i].classList.toggle("btn-outline-secondary", !dangChon);
    }
}

function khoiTaoTinTuc() {
    var loc = document.getElementById("news-filter");
    if (loc) {
        loc.addEventListener("click", function (e) {
            var nut = e.target.closest("button");
            if (nut) { hienDanhSachTin(nut.getAttribute("data-loai") || ""); }
        });
    }
    var q = /[?&]loai=(tintuc|khuyenmai)/.exec(location.search);
    hienDanhSachTin(q ? q[1] : "");
}

/* Bấm "Đọc tiếp" ở bất kỳ trang nào: ghi currentNews trước khi chuyển sang chitiet-tintuc.html */
document.addEventListener("click", function (e) {
    var a = e.target.closest ? e.target.closest(".tin-link") : null;
    if (a) {
        try { localStorage.setItem("currentNews", a.getAttribute("data-id")); } catch (err) {}
    }
});